import Foundation

/// A read-only file mapped into memory for the life of the process. The
/// pages are clean and file-backed, so iOS can drop and refetch them under
/// pressure and does not count them against the keyboard extension's
/// memory limit, which is what lets a 165k-word list ride along in a
/// process with a 55MB ceiling.
struct MappedFile: @unchecked Sendable {
    let base: UnsafeRawPointer

    init(url: URL) {
        let fd = open(url.path, O_RDONLY)
        precondition(fd >= 0, "cannot open \(url.path)")
        var info = stat()
        precondition(fstat(fd, &info) == 0, "cannot stat \(url.path)")
        let mapped = mmap(nil, Int(info.st_size), PROT_READ, MAP_PRIVATE, fd, 0)
        close(fd)
        precondition(mapped != MAP_FAILED, "cannot map \(url.path)")
        self.base = UnsafeRawPointer(mapped!)
    }

    /// A table the engine ships: `Resources/<name>.bin`, generated by
    /// `engine/tools/gen-<name>.py`. Every table opens with a four-byte
    /// magic and a u32 version; a reader and a file that disagree on the
    /// layout stop here instead of reading garbage.
    static func resource(_ name: String, magic: String, version: Int) -> MappedFile {
        guard let url = Bundle.module.url(forResource: name, withExtension: "bin") else {
            fatalError("\(name).bin is missing from the TypingEngine resources; "
                       + "run engine/tools/gen-\(name).py")
        }
        let file = MappedFile(url: url)
        let found = String(decoding: file.bytes(at: 0, count: 4), as: UTF8.self)
        precondition(found == magic && file.u32(at: 4) == version,
                     "\(name).bin is \(found) v\(file.u32(at: 4)); this build reads "
                     + "\(magic) v\(version). Run engine/tools/gen-\(name).py")
        return file
    }

    func u32(at offset: Int) -> Int {
        Int(base.loadUnaligned(fromByteOffset: offset, as: UInt32.self))
    }

    func u8(at offset: Int) -> Int {
        Int(base.load(fromByteOffset: offset, as: UInt8.self))
    }

    func bytes(at offset: Int, count: Int) -> UnsafeBufferPointer<UInt8> {
        UnsafeBufferPointer(start: base.advanced(by: offset).assumingMemoryBound(to: UInt8.self),
                            count: count)
    }

    /// A run of little-endian u32 values.
    func u32s(at offset: Int, count: Int) -> UnsafeRawBufferPointer {
        UnsafeRawBufferPointer(start: base.advanced(by: offset), count: 4 * count)
    }

    /// The first position in `0..<count` whose entry does not satisfy
    /// `before`, given that `before` holds for a prefix of the positions and
    /// then fails. The one binary search both tables use.
    static func partition(count: Int, before: (Int) -> Bool) -> Int {
        var low = 0, high = count
        while low < high {
            let mid = (low + high) / 2
            if before(mid) { low = mid + 1 } else { high = mid }
        }
        return low
    }
}

extension UnsafeRawBufferPointer {
    /// The u32 at position `i` of a run started by `MappedFile.u32s`.
    func u32(_ i: Int) -> Int {
        Int(loadUnaligned(fromByteOffset: 4 * i, as: UInt32.self))
    }
}
