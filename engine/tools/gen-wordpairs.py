#!/usr/bin/env python3
"""Regenerate WordPairs: the engine's word-pair table, which is how a
correction reads the word before it (unit 4a of specs/autocorrect-parity.md).

The counts are Norvig's `count_2w.txt` (`engine/tools/vendor/count_2w.txt.gz`,
the quarter-million most frequent bigrams of the Google Web Trillion Word
Corpus). A pair is kept when both words are in WordRank, because a word the
engine cannot propose never needs a pair, and when its count reaches the
floor.

The floor is 300,000. The weakest split stock made in the recorded
missed-space slice that the counts hold at all is "breakfast is" at 346,954,
and "bad ass" sits at 204,647: a floor between them keeps "badass", a
protection row the 2014 word list does not know, from splitting.

Run from the repo root:

    python3 engine/tools/gen-wordpairs.py
"""
import gzip
import importlib.util
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TARGET = ROOT / "engine" / "Sources" / "TypingEngine" / "WordPairs.swift"
SOURCE = ROOT / "engine" / "tools" / "vendor" / "count_2w.txt.gz"
FLOOR = 300_000


def wordrank_words() -> set:
    """The lowercase vocabulary WordRank is generated from."""
    spec = importlib.util.spec_from_file_location(
        "gen_wordrank", Path(__file__).with_name("gen-wordrank.py"))
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return {word.lower() for word in module.build()}


def pairs(vocabulary: set) -> list:
    kept = []
    with gzip.open(SOURCE, "rt", encoding="utf-8") as handle:
        for line in handle:
            bigram, count = line.rstrip("\n").split("\t")
            count = int(count)
            if count < FLOOR:
                continue
            first, second = bigram.split(" ")
            if first.isalpha() and second.isalpha() \
                    and first in vocabulary and second in vocabulary:
                kept.append((first, second, count))
    if not kept:
        sys.exit(f"{SOURCE} held no pairs")
    # Count first, then alphabetical, so the order is total and a
    # regeneration reproduces the file byte for byte.
    kept.sort(key=lambda row: (-row[2], row[0], row[1]))
    return kept


def main():
    if not SOURCE.exists():
        sys.exit(f"{SOURCE} is missing; see engine/tools/vendor/NOTICE")
    rows = pairs(wordrank_words())
    body = " ".join(f"{a} {b} {c}" for a, b, c in rows)
    TARGET.write_text(f'''// GENERATED by engine/tools/gen-wordpairs.py -- do not hand-edit.
// Norvig's web bigram counts, kept where both words are in WordRank and the
// count reaches {FLOOR:,}. Provenance and limits in
// engine/tools/vendor/NOTICE. {len(rows)} pairs.

/// The engine's word-pair table: how often one word follows another in web
/// text. `WordPairModel` reads it to rank correction candidates by the word
/// before them.
enum WordPairs {{
    /// Count keyed by "first second", both lowercase.
    static let counts: [String: Int] = {{
        var table: [String: Int] = [:]
        table.reserveCapacity({len(rows)})
        let fields = list.split(separator: " ")
        var i = 0
        while i + 2 < fields.count {{
            table["\\(fields[i]) \\(fields[i + 1])"] = Int(fields[i + 2])
            i += 3
        }}
        return table
    }}()

    private static let list = "{body}"
}}
''')
    print(f"WordPairs: {len(rows)} pairs at or above {FLOOR:,}")


if __name__ == "__main__":
    main()
