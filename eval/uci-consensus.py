#!/usr/bin/env python3
"""Build RealCorpusV3.swift: adjudicated relabel of the frozen UCI set.

Gold = majority of 3 blind annotators; a 3-way split falls back to the
original sender label (spec eval-v3 criterion 6). Split membership (dev/test)
is preserved from v2.1: indices 0-318 dev, 319-637 test. Original rows are
never edited; this emits a NEW set.
"""
import collections
import re

SRC = "engine/Tests/PunctuationEngineTests/RealCorpus.swift"
VALID = {".", "?", "!", ",", '"'}


def sender_labels():
    src = open(SRC).read()
    rows = re.findall(r'\("((?:[^"\\]|\\.)*)",\s*"((?:[^"\\]|\\.)*)"\)', src)
    return [(t, l.replace('\\"', '"')) for t, l in rows]


def load_ann(path):
    out = {}
    for line in open(path):
        i, l = line.rstrip("\n").split("\t")
        out[int(i)] = l
    return out


def main():
    rows = sender_labels()
    assert len(rows) == 638, len(rows)
    anns = [load_ann(f"eval/raw/uci-ann{k}.tsv") for k in (1, 2, 3)]

    out_rows, ties, changed = [], 0, 0
    agree3 = 0
    for i, (text, sender) in enumerate(rows):
        votes = [anns[k][i] for k in range(3)]
        count = collections.Counter(votes)
        label, freq = count.most_common(1)[0]
        if freq == 1:
            label = sender
            ties += 1
        if freq == 3:
            agree3 += 1
        if label != sender:
            changed += 1
        out_rows.append((text, label, votes))

    def emit(name, subset):
        lines = [f"let {name}: [EvalRow] = ["]
        for text, label, _ in subset:
            esc_label = label.replace('"', '\\"')
            lines.append(f'    EvalRow(text: "{text}", label: "{esc_label}", '
                         f'form: "real-sms", register: "real"),')
        lines.append("]")
        return "\n".join(lines)

    header = (
        "// GENERATED by eval/uci-consensus.py -- do not hand-edit rows.\n"
        "// Real-SMS set v3: same 638 UCI sentences as v2.1, gold relabeled by\n"
        "// majority of 3 blind annotators (3-way splits keep the sender label).\n"
        "// Split membership preserved from v2.1. FROZEN: rows never change in\n"
        "// a commit that touches engine source.\n"
        f"// 3/3 agreement {agree3}/638, ties->sender {ties}, labels changed vs sender {changed}.\n\n")
    with open("engine/Tests/PunctuationEngineTests/RealCorpusV3.swift", "w") as f:
        f.write(header + emit("realV3Dev", out_rows[:319]) + "\n\n"
                + emit("realV3Test", out_rows[319:]) + "\n")

    dist = collections.Counter(l for _, l, _ in out_rows)
    print(f"3/3 agree: {agree3}/638  ties->sender: {ties}  changed vs sender: {changed}")
    print("label distribution:", dict(sorted(dist.items())))


if __name__ == "__main__":
    main()
