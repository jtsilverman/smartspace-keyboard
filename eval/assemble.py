#!/usr/bin/env python3
"""Assemble the blind benchmark from the raw pool + 3 blind annotations.

Gold label = majority of the 3 blind annotators (generator intent is metadata,
not a vote). Three-way disagreement -> ambiguity slice (top-2 scoring only).
Exact-duplicate texts: dropped entirely if their generator intents conflict,
kept once otherwise. Split is stratified by (form, gold) with a fixed seed.

Usage: assemble.py pool.tsv ann1.tsv ann2.tsv ann3.tsv out_dir
Writes: BlindCorpus.swift, blind-labeled.tsv, assembly-report.txt
"""
import collections
import random
import sys
import zlib


def load_pool(path):
    rows = []
    with open(path) as f:
        for line in f:
            parts = line.rstrip("\n").split("\t")
            if len(parts) == 4:
                intent, form, register, text = parts
                rows.append({"intent": intent, "form": form,
                             "register": register, "text": text})
    return rows


def load_annotations(path, n):
    labels = {}
    with open(path) as f:
        for line in f:
            parts = line.rstrip("\n").split("\t")
            if len(parts) == 2 and parts[0].isdigit():
                labels[int(parts[0])] = parts[1]
    missing = [i for i in range(n) if i not in labels]
    if missing:
        raise SystemExit(f"{path}: missing indices {missing[:5]}... ({len(missing)})")
    return labels


def swift_escape(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


def main():
    pool_path, a1, a2, a3, out_dir = sys.argv[1:6]
    pool = load_pool(pool_path)
    n = len(pool)
    anns = [load_annotations(p, n) for p in (a1, a2, a3)]

    # dedupe exact texts
    by_text = collections.defaultdict(list)
    for i, row in enumerate(pool):
        by_text[row["text"]].append(i)
    drop = set()
    for text, idxs in by_text.items():
        if len(idxs) > 1:
            intents = {pool[i]["intent"] for i in idxs}
            if len(intents) > 1:
                drop.update(idxs)          # conflicting intents: drop all
            else:
                drop.update(idxs[1:])      # same intent: keep first

    consensus, ambiguous = [], []
    intent_disagree = 0
    valid = {".", "?", "!", ",", '"'}
    for i, row in enumerate(pool):
        if i in drop:
            continue
        votes = [anns[k][i] for k in range(3)]
        if any(v not in valid for v in votes):
            raise SystemExit(f"row {i}: invalid vote {votes}")
        count = collections.Counter(votes)
        label, freq = count.most_common(1)[0]
        rec = dict(row, gold=label, votes="".join(votes))
        if freq == 1:
            ambiguous.append(rec)
        else:
            if label != row["intent"]:
                intent_disagree += 1
            consensus.append(rec)

    # stratified split by (form, gold)
    rng = random.Random(7)
    dev, test = [], []
    groups = collections.defaultdict(list)
    for rec in consensus:
        groups[(rec["form"], rec["gold"])].append(rec)
    for key in sorted(groups):
        rows = groups[key]
        rng.shuffle(rows)
        half = len(rows) // 2
        extra = len(rows) - 2 * half
        # odd rows alternate which half gets the extra; crc32 is stable across
        # processes (Python randomizes hash() per run, which broke reproducibility)
        if extra and (zlib.crc32("|".join(key).encode()) % 2 == 0):
            dev.extend(rows[:half + extra]); test.extend(rows[half + extra:])
        else:
            dev.extend(rows[:half]); test.extend(rows[half:])

    def emit_array(name, rows):
        lines = [f"let {name}: [EvalRow] = ["]
        for r in rows:
            lines.append(f'    EvalRow(text: "{swift_escape(r["text"])}", '
                         f'label: "{swift_escape(r["gold"])}", '
                         f'form: "{r["form"]}", register: "{r["register"]}"),')
        lines.append("]")
        return "\n".join(lines)

    header = (
        "// GENERATED by eval/assemble.py -- do not hand-edit rows.\n"
        "// Blind benchmark v1: sentences authored by fresh-context generators\n"
        "// with no engine access; gold = majority of 3 blind annotators.\n"
        "// FROZEN: rows never change in a commit that touches engine source.\n"
        f"// Pool {n}, dropped dupes {len(drop)}, consensus {len(consensus)}, "
        f"ambiguous {len(ambiguous)}.\n\n")
    with open(f"{out_dir}/BlindCorpus.swift", "w") as f:
        f.write(header + emit_array("blindCorpusDev", dev) + "\n\n"
                + emit_array("blindCorpusTest", test) + "\n\n"
                + emit_array("blindAmbiguous", ambiguous) + "\n")

    with open("eval/blind-labeled.tsv", "w") as f:
        for rec in consensus + ambiguous:
            slice_ = "ambiguous" if rec in ambiguous else "consensus"
            f.write("\t".join([rec["gold"], rec["votes"], rec["intent"],
                               rec["form"], rec["register"], slice_,
                               rec["text"]]) + "\n")

    label_dist = collections.Counter(r["gold"] for r in consensus)
    with open("eval/assembly-report.txt", "w") as f:
        f.write(f"pool={n} dropped_dup_rows={len(drop)} consensus={len(consensus)} "
                f"ambiguous={len(ambiguous)} intent_vs_consensus_disagreements={intent_disagree}\n")
        f.write(f"label distribution: {dict(sorted(label_dist.items()))}\n")
        f.write(f"dev={len(dev)} test={len(test)}\n")
        for lab in sorted(valid):
            d = sum(1 for r in dev if r["gold"] == lab)
            t = sum(1 for r in test if r["gold"] == lab)
            f.write(f"  {lab}: dev {d} / test {t}\n")
    print(open("eval/assembly-report.txt").read())


if __name__ == "__main__":
    main()
